-- =============================================================
-- Client support & maintenance ticketing
--
-- Multi-tenant model:
--   client_orgs   -> the client company (created by us when a deal closes)
--   client_sites  -> one or more websites belonging to an org
--   client_members-> auth users linked to an org
--   support_tickets -> a ticket belongs to one org (+ optional site)
--
-- The API uses the service_role key (bypasses RLS) and is the only
-- reader/writer. RLS is enabled with no policies (fail-closed).
-- =============================================================

-- ------------------------------------------------------------------
-- client_orgs: the client company profile
-- ------------------------------------------------------------------
create table if not exists public.client_orgs (
  id                    uuid        primary key default gen_random_uuid(),
  name                  text        not null,
  slug                  text        unique,
  primary_contact_name  text,
  contact_email         text,
  contact_phone         text,
  status                text        not null default 'active'
                          check (status in ('active', 'suspended', 'archived')),
  support_enabled       boolean     not null default true,
  notes                 text,
  related_quotation_id  uuid        references public.quotations (id) on delete set null,
  created_by            uuid        references public.admin_users (id) on delete set null,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create index if not exists client_orgs_status_idx on public.client_orgs (status);
create index if not exists client_orgs_name_idx   on public.client_orgs (lower(name));

-- ------------------------------------------------------------------
-- client_sites: websites belonging to an org (one org -> many sites)
-- ------------------------------------------------------------------
create table if not exists public.client_sites (
  id          uuid        primary key default gen_random_uuid(),
  org_id      uuid        not null references public.client_orgs (id) on delete cascade,
  label       text        not null,
  url         text        not null,
  status      text        not null default 'live'
                check (status in ('live', 'maintenance', 'offline', 'archived')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists client_sites_org_idx on public.client_sites (org_id);

-- ------------------------------------------------------------------
-- client_members: portal users linked to an org (one org per user)
-- ------------------------------------------------------------------
create table if not exists public.client_members (
  id          uuid        primary key default gen_random_uuid(),
  org_id      uuid        not null references public.client_orgs (id) on delete cascade,
  user_id     uuid        not null references auth.users (id) on delete cascade,
  email       text        not null,
  full_name   text,
  role        text        not null default 'member'
                check (role in ('admin', 'member')),
  status      text        not null default 'active'
                check (status in ('invited', 'active', 'disabled')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (user_id)
);

create index if not exists client_members_org_idx   on public.client_members (org_id);
create index if not exists client_members_email_idx on public.client_members (lower(email));

-- ------------------------------------------------------------------
-- client_invites: single-use invite codes for client users
-- ------------------------------------------------------------------
create table if not exists public.client_invites (
  id          uuid        primary key default gen_random_uuid(),
  org_id      uuid        not null references public.client_orgs (id) on delete cascade,
  email       text        not null,
  role        text        not null default 'member'
                check (role in ('admin', 'member')),
  invited_by  uuid        references public.admin_users (id) on delete set null,
  used        boolean     not null default false,
  used_at     timestamptz,
  used_by     uuid        references auth.users (id) on delete set null,
  expires_at  timestamptz,
  created_at  timestamptz not null default now()
);

create unique index if not exists client_invites_pending_email_idx
  on public.client_invites (org_id, lower(email)) where used = false;
create index if not exists client_invites_email_idx on public.client_invites (lower(email));

-- ------------------------------------------------------------------
-- support_tickets: human-friendly number generated by a sequence
-- ------------------------------------------------------------------
create sequence if not exists public.support_ticket_seq;

create table if not exists public.support_tickets (
  id                    uuid        primary key default gen_random_uuid(),
  number                text        not null unique,
  org_id                uuid        not null references public.client_orgs (id) on delete cascade,
  site_id               uuid        references public.client_sites (id) on delete set null,
  created_by            uuid        references public.client_members (id) on delete set null,
  subject               text        not null,
  category              text        not null default 'support'
                          check (category in ('support', 'maintenance', 'bug', 'request', 'other')),
  priority              text        not null default 'normal'
                          check (priority in ('low', 'normal', 'high', 'urgent')),
  status                text        not null default 'open'
                          check (status in ('open', 'in_progress', 'waiting_on_client', 'resolved', 'closed')),
  assigned_to           uuid        references public.admin_users (id) on delete set null,
  related_quotation_id  uuid        references public.quotations (id) on delete set null,
  last_message_at       timestamptz not null default now(),
  first_response_at     timestamptz,
  resolved_at           timestamptz,
  closed_at             timestamptz,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create index if not exists support_tickets_org_status_idx on public.support_tickets (org_id, status);
create index if not exists support_tickets_assignee_idx   on public.support_tickets (assigned_to, status);
create index if not exists support_tickets_activity_idx   on public.support_tickets (last_message_at desc);
create index if not exists support_tickets_open_idx       on public.support_tickets (status)
  where status in ('open', 'in_progress', 'waiting_on_client');

-- ------------------------------------------------------------------
-- support_messages: public replies + internal (agent-only) notes
-- ------------------------------------------------------------------
create table if not exists public.support_messages (
  id           uuid        primary key default gen_random_uuid(),
  ticket_id    uuid        not null references public.support_tickets (id) on delete cascade,
  author_type  text        not null
                 check (author_type in ('client', 'agent', 'system')),
  author_id    uuid,
  author_name  text,
  body         text        not null,
  is_internal  boolean     not null default false,
  created_at   timestamptz not null default now()
);

create index if not exists support_messages_ticket_idx on public.support_messages (ticket_id, created_at);

-- ------------------------------------------------------------------
-- support_attachments: files stored in the support-attachments bucket
-- ------------------------------------------------------------------
create table if not exists public.support_attachments (
  id            uuid        primary key default gen_random_uuid(),
  ticket_id     uuid        not null references public.support_tickets (id) on delete cascade,
  message_id    uuid        references public.support_messages (id) on delete cascade,
  storage_path  text        not null,
  file_name     text        not null,
  mime_type     text,
  size_bytes    bigint,
  uploaded_by   uuid,
  created_at    timestamptz not null default now()
);

create index if not exists support_attachments_ticket_idx on public.support_attachments (ticket_id);

-- ------------------------------------------------------------------
-- support_events: ticket timeline (status/priority/assignment)
-- ------------------------------------------------------------------
create table if not exists public.support_events (
  id          bigint      generated always as identity primary key,
  ticket_id   uuid        not null references public.support_tickets (id) on delete cascade,
  actor_type  text        not null default 'system'
                check (actor_type in ('client', 'agent', 'system')),
  actor_id    uuid,
  type        text        not null,
  from_value  text,
  to_value    text,
  created_at  timestamptz not null default now()
);

create index if not exists support_events_ticket_idx on public.support_events (ticket_id, created_at);

-- ------------------------------------------------------------------
-- Ticket number: R365-T-0001
-- ------------------------------------------------------------------
create or replace function public.set_support_ticket_number()
returns trigger
language plpgsql
as $$
begin
  if new.number is null or new.number = '' then
    new.number := 'R365-T-' || lpad(nextval('public.support_ticket_seq')::text, 4, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists set_support_ticket_number on public.support_tickets;
create trigger set_support_ticket_number
  before insert on public.support_tickets
  for each row execute function public.set_support_ticket_number();

-- ------------------------------------------------------------------
-- updated_at maintenance
-- ------------------------------------------------------------------
drop trigger if exists set_updated_at on public.client_orgs;
create trigger set_updated_at
  before update on public.client_orgs
  for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at on public.client_sites;
create trigger set_updated_at
  before update on public.client_sites
  for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at on public.client_members;
create trigger set_updated_at
  before update on public.client_members
  for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at on public.support_tickets;
create trigger set_updated_at
  before update on public.support_tickets
  for each row execute function public.set_updated_at();

-- ------------------------------------------------------------------
-- RLS: fail-closed (API uses service_role)
-- ------------------------------------------------------------------
alter table public.client_orgs        enable row level security;
alter table public.client_sites       enable row level security;
alter table public.client_members     enable row level security;
alter table public.client_invites     enable row level security;
alter table public.support_tickets    enable row level security;
alter table public.support_messages   enable row level security;
alter table public.support_attachments enable row level security;
alter table public.support_events     enable row level security;

revoke all on public.client_orgs         from anon, authenticated;
revoke all on public.client_sites        from anon, authenticated;
revoke all on public.client_members      from anon, authenticated;
revoke all on public.client_invites      from anon, authenticated;
revoke all on public.support_tickets     from anon, authenticated;
revoke all on public.support_messages    from anon, authenticated;
revoke all on public.support_attachments from anon, authenticated;
revoke all on public.support_events      from anon, authenticated;

revoke all on sequence public.support_ticket_seq from anon, authenticated;
grant usage, select on sequence public.support_ticket_seq to service_role;

-- ------------------------------------------------------------------
-- Storage bucket for attachments (private; served via signed URLs)
-- ------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('support-attachments', 'support-attachments', false)
on conflict (id) do nothing;
